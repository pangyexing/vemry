//! OpenAI-compatible Chat Completions wire types (request, streaming chunks).

use serde::{Deserialize, Serialize};

/// A message body: plain text, or multi-modal content parts (the OpenAI array
/// shape). untagged: a bare string ↔ `Text` (so the bytes of an old sidecar and
/// of a Chat Completions request body are unchanged), an array ↔ `Parts`. Only a
/// user envelope carrying images is `Parts`; every other message is always
/// `Text`.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(untagged)]
pub enum Content {
    Text(String),
    Parts(Vec<Part>),
}

/// The three states of a content part. `ImageRef` is the **persisted form**:
/// history and sidecar store only the vault path (disk is the single source of
/// truth, base64 never touches it); when the runner assembles a request it fills
/// that in — inside the privacy gate — as an `ImageUrl` (the **wire form**, which
/// never enters history). Actually sending `image_ref` over the wire earns a 400
/// from the server; that is the safety net for "forgot to fill it in", not a
/// compatibility problem.
#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Part {
    Text { text: String },
    ImageRef { path: String },
    ImageUrl { image_url: ImageUrl },
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ImageUrl {
    pub url: String,
}

impl Content {
    /// The text view: the whole string for `Text`; the first Text part for
    /// `Parts` (a user envelope always has its body first and images after).
    /// Compaction, source extraction and title derivation only look at this face.
    pub fn text(&self) -> Option<&str> {
        match self {
            Content::Text(s) => Some(s),
            Content::Parts(parts) => parts.iter().find_map(|p| match p {
                Part::Text { text } => Some(text.as_str()),
                _ => None,
            }),
        }
    }

    /// The mutable face of `text()` (same rule: the first Text part is the body);
    /// used by `scrub_private_refs` to rewrite an envelope in place.
    pub fn text_mut(&mut self) -> Option<&mut String> {
        match self {
            Content::Text(s) => Some(s),
            Content::Parts(parts) => parts.iter_mut().find_map(|p| match p {
                Part::Text { text } => Some(text),
                _ => None,
            }),
        }
    }

    /// Append text (the runner's budget epilogue): for `Parts` it appends to the
    /// last Text part, adding one when there is none.
    pub fn push_str(&mut self, s: &str) {
        match self {
            Content::Text(t) => t.push_str(s),
            Content::Parts(parts) => match parts.iter_mut().rev().find_map(|p| match p {
                Part::Text { text } => Some(text),
                _ => None,
            }) {
                Some(t) => t.push_str(s),
                None => parts.push(Part::Text { text: s.to_string() }),
            },
        }
    }

    /// Test-only accessor (production paths match on `Content::Parts` directly).
    #[cfg(test)]
    pub fn parts(&self) -> Option<&[Part]> {
        match self {
            Content::Text(_) => None,
            Content::Parts(p) => Some(p),
        }
    }
}

impl From<String> for Content {
    fn from(s: String) -> Self {
        Content::Text(s)
    }
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ChatMessage {
    pub role: String, // system | user | assistant | tool
    #[serde(skip_serializing_if = "Option::is_none")]
    pub content: Option<Content>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<ToolCall>>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,
    /// A hard contract of DeepSeek V3.2+ thinking mode: on an assistant turn that
    /// carries tool_calls, `reasoning_content` must be sent back with the history
    /// verbatim, and leaving it out is an immediate 400 ("must be passed back").
    /// Other OpenAI-compatible endpoints ignore unknown fields as usual; in the
    /// Responses shape this role is played by the reasoning item in extra_items,
    /// so it is not mapped twice.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reasoning_content: Option<String>,
    /// Opaque blocks of the Anthropic-format line (a `server_tool_use`, a
    /// `web_search_tool_result` with its encrypted results, the signature stub of
    /// a thinking block), replayed on the next turn as that line requires, which
    /// is how the server restores the search results. serde(skip): Chat
    /// Completions serialisation is unaffected; only AnthropicTransport reads and
    /// writes it (an older session may still hold a Responses `web_search_call`
    /// here, which that transport leaves out).
    #[serde(skip)]
    pub extra_items: Vec<serde_json::Value>,
    /// The turn id: generated by the runner at the head of a turn and stamped on
    /// the user envelope message alone. The user line of the audit jsonl and the
    /// UI timeline carry the same id, and forking locates by it — three layers
    /// each counting user ordinals would fall out of step after a compaction
    /// synthesises a message or an edit is re-sent. skip_serializing: it must
    /// never enter an API request body (an unknown parameter risks a 400); the
    /// sidecar gets it written by hand in write_history, and reading back uses
    /// serde's default deserialisation.
    #[serde(default, skip_serializing)]
    pub turn: Option<String>,
    /// Metadata (kind/path) of the references successfully injected into the
    /// envelope: the source of truth `scrub_private_refs` locates by — fence_attr
    /// is a lossy escaping, and a pathological file name cannot be recovered from
    /// the envelope text. skip_serializing keeps it out of the request body; the
    /// sidecar gets it written by hand in write_history, and reading back uses
    /// serde's default deserialisation (an existing old sidecar yields an empty
    /// vec, and the envelope scan covers that case).
    #[serde(default, skip_serializing)]
    pub context_refs: Vec<StoredRef>,
}

/// An element of `ChatMessage::context_refs`: the kind string and the real path
/// only, never the content.
#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
pub struct StoredRef {
    pub kind: String,
    pub path: String,
}

impl ChatMessage {
    pub fn system(text: impl Into<String>) -> Self {
        ChatMessage {
            role: "system".into(),
            content: Some(Content::Text(text.into())),
            tool_calls: None,
            tool_call_id: None,
            reasoning_content: None,
            extra_items: vec![],
            turn: None,
            context_refs: vec![],
        }
    }
    pub fn user(text: impl Into<String>) -> Self {
        ChatMessage {
            role: "user".into(),
            content: Some(Content::Text(text.into())),
            tool_calls: None,
            tool_call_id: None,
            reasoning_content: None,
            extra_items: vec![],
            turn: None,
            context_refs: vec![],
        }
    }
    /// A user envelope carrying images (when compose_user_message returns Parts);
    /// plain text still goes through `user`.
    pub fn user_content(content: Content) -> Self {
        ChatMessage {
            role: "user".into(),
            content: Some(content),
            tool_calls: None,
            tool_call_id: None,
            reasoning_content: None,
            extra_items: vec![],
            turn: None,
            context_refs: vec![],
        }
    }
    pub fn assistant(text: Option<String>, tool_calls: Option<Vec<ToolCall>>) -> Self {
        ChatMessage {
            role: "assistant".into(),
            content: text.map(Content::Text),
            tool_calls,
            tool_call_id: None,
            reasoning_content: None,
            extra_items: vec![],
            turn: None,
            context_refs: vec![],
        }
    }
    pub fn tool_result(tool_call_id: impl Into<String>, content: impl Into<String>) -> Self {
        ChatMessage {
            role: "tool".into(),
            content: Some(Content::Text(content.into())),
            tool_calls: None,
            tool_call_id: Some(tool_call_id.into()),
            reasoning_content: None,
            extra_items: vec![],
            turn: None,
            context_refs: vec![],
        }
    }
    /// The text view of the body (see `Content::text`).
    pub fn text(&self) -> Option<&str> {
        self.content.as_ref().and_then(Content::text)
    }
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ToolCall {
    pub id: String,
    #[serde(rename = "type")]
    pub kind: String, // "function"
    pub function: FunctionCall,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct FunctionCall {
    pub name: String,
    /// JSON-encoded arguments string, per the OpenAI protocol.
    pub arguments: String,
}

/// A tool declaration. untagged: Function serialises as OpenAI's
/// {"type":"function",...}; Raw is the pass-through for a server-side built-in
/// tool (the Responses API's {"type":"web_search"}, for instance).
#[derive(Clone, Debug, Serialize)]
#[serde(untagged)]
pub enum ToolDef {
    Function {
        #[serde(rename = "type")]
        kind: String, // "function"
        function: FunctionSpec,
    },
    Raw(serde_json::Value),
}

impl ToolDef {
    pub fn function(function: FunctionSpec) -> Self {
        ToolDef::Function { kind: "function".into(), function }
    }

    /// The spec of the Function variant (Raw returns None).
    pub fn as_function(&self) -> Option<&FunctionSpec> {
        match self {
            ToolDef::Function { function, .. } => Some(function),
            ToolDef::Raw(_) => None,
        }
    }
}

#[derive(Clone, Debug, Serialize)]
pub struct FunctionSpec {
    pub name: String,
    pub description: String,
    pub parameters: serde_json::Value,
}

#[derive(Clone, Debug, Serialize)]
pub struct ChatRequest {
    pub model: String,
    pub messages: Vec<ChatMessage>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tools: Option<Vec<ToolDef>>,
    pub stream: bool,
    /// `{"include_usage": true}`: the streaming tail carries usage (token counts,
    /// cache hits). Sent only to endpoints known to support it (DeepSeek) — Zhipu
    /// streams carry usage by default, and sending an unknown parameter risks a
    /// 400 instead; the Responses shape ignores this field.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub stream_options: Option<serde_json::Value>,
    /// Thinking depth (DeepSeek's official low/high/max levels). The official
    /// Chat Completions shape has no "none" level, so turning thinking off goes
    /// through `thinking:{"type":"disabled"}` — runner::effort_fields decides
    /// between the two fields, which are never both Some; on a non-DeepSeek
    /// endpoint it is always None (an unknown parameter risks a 400, the same gate
    /// as stream_options). The Responses line does not serialise this struct
    /// directly: responses_request_body maps it to `reasoning:{effort}` (covering
    /// all four of none/low/high/max).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub reasoning_effort: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub thinking: Option<serde_json::Value>,
}

// ---- streaming chunks ----

#[derive(Clone, Debug, Default, Deserialize)]
pub struct StreamChunk {
    #[serde(default)]
    pub choices: Vec<StreamChoice>,
    /// Web search results (AnthropicTransport composes them from a
    /// `web_search_tool_result` block; should a field of the same name appear in
    /// a Chat Completions stream, this catches it defensively too).
    #[serde(default)]
    pub web_search: Option<Vec<WebSearchResult>>,
    /// Search progress (a `server_tool_use` block starting, its result arriving).
    #[serde(default)]
    pub web_search_status: Option<WebSearchStatus>,
    /// The queries the server actually ran (a `server_tool_use` block's input).
    #[serde(default)]
    pub web_search_queries: Option<Vec<String>>,
    /// Blocks that must be replayed next turn (see `ChatMessage::extra_items`).
    #[serde(default)]
    pub raw_items: Option<Vec<serde_json::Value>>,
    /// Token counts. Chat Completions puts them in the final streaming chunk
    /// (Zhipu by default; DeepSeek once stream_options.include_usage is on);
    /// Responses composes them from response.completed.
    #[serde(default)]
    pub usage: Option<Usage>,
}

/// The token counts of one request. The cache fields are tolerant of both
/// spellings: DeepSeek puts `prompt_cache_hit_tokens` at the top level, the
/// OpenAI style uses `prompt_tokens_details.cached_tokens` — `cache_hit_tokens()`
/// reads whichever is there.
#[derive(Clone, Debug, Default, Deserialize)]
pub struct Usage {
    #[serde(default, alias = "input_tokens")]
    pub prompt_tokens: u64,
    #[serde(default, alias = "output_tokens")]
    pub completion_tokens: u64,
    #[serde(default)]
    pub prompt_cache_hit_tokens: Option<u64>,
    #[serde(default, alias = "input_tokens_details")]
    pub prompt_tokens_details: Option<UsageDetails>,
    /// The server-side searches this call ran (the Anthropic-format line reports
    /// them; the other lines have none).
    #[serde(default)]
    pub web_search_requests: Option<u64>,
}

#[derive(Clone, Debug, Default, Deserialize)]
pub struct UsageDetails {
    #[serde(default)]
    pub cached_tokens: Option<u64>,
}

impl Usage {
    pub fn cache_hit_tokens(&self) -> u64 {
        self.prompt_cache_hit_tokens
            .or_else(|| self.prompt_tokens_details.as_ref().and_then(|d| d.cached_tokens))
            .unwrap_or(0)
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum WebSearchStatus {
    Searching,
    Completed,
}

/// One search source. The fields carry tolerant aliases (link/content and so on);
/// the exact shape is whatever live testing shows.
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct WebSearchResult {
    #[serde(default)]
    pub title: String,
    #[serde(default, alias = "link")]
    pub url: String,
    #[serde(default, alias = "content", alias = "snippet")]
    pub snippet: String,
    #[serde(default)]
    pub publish_date: Option<String>,
}

#[derive(Clone, Debug, Default, Deserialize)]
pub struct StreamChoice {
    #[serde(default)]
    pub delta: Delta,
    #[serde(default)]
    pub finish_reason: Option<String>,
}

#[derive(Clone, Debug, Default, Deserialize)]
pub struct Delta {
    #[serde(default)]
    pub content: Option<String>,
    /// Zhipu GLM thinking models stream reasoning here.
    #[serde(default)]
    pub reasoning_content: Option<String>,
    #[serde(default)]
    pub tool_calls: Option<Vec<ToolCallDelta>>,
}

#[derive(Clone, Debug, Deserialize)]
pub struct ToolCallDelta {
    #[serde(default)]
    pub index: Option<usize>,
    #[serde(default)]
    pub id: Option<String>,
    #[serde(default)]
    pub function: Option<FunctionDelta>,
}

#[derive(Clone, Debug, Deserialize)]
pub struct FunctionDelta {
    #[serde(default)]
    pub name: Option<String>,
    #[serde(default)]
    pub arguments: Option<String>,
}

/// Accumulates tool-call deltas (indexed fragments) into complete calls.
#[derive(Default)]
pub struct ToolCallAccumulator {
    calls: Vec<(String, String, String)>, // (id, name, arguments)
}

impl ToolCallAccumulator {
    pub fn push(&mut self, d: &ToolCallDelta) {
        let idx = d.index.unwrap_or_else(|| self.calls.len().saturating_sub(1));
        while self.calls.len() <= idx {
            self.calls.push((String::new(), String::new(), String::new()));
        }
        let slot = &mut self.calls[idx];
        if let Some(id) = &d.id {
            slot.0.push_str(id);
        }
        if let Some(f) = &d.function {
            if let Some(n) = &f.name {
                slot.1.push_str(n);
            }
            if let Some(a) = &f.arguments {
                slot.2.push_str(a);
            }
        }
    }

    pub fn is_empty(&self) -> bool {
        self.calls.is_empty()
    }

    pub fn finish(self) -> Vec<ToolCall> {
        self.calls
            .into_iter()
            .enumerate()
            .filter(|(_, (_, name, _))| !name.is_empty())
            .map(|(i, (id, name, arguments))| ToolCall {
                id: if id.is_empty() { format!("call_{i}") } else { id },
                kind: "function".into(),
                function: FunctionCall { name, arguments },
            })
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    /// A plain-text message still goes over the wire as a bare string (the bytes
    /// of an old sidecar or request body are unchanged) and reads back as Text.
    #[test]
    fn content_text_is_bare_string_on_wire_and_back() {
        let m = ChatMessage::user("hi");
        let v = serde_json::to_value(&m).unwrap();
        assert_eq!(v["content"], "hi");
        let back: ChatMessage = serde_json::from_value(v).unwrap();
        assert_eq!(back.text(), Some("hi"));
        assert!(back.content.as_ref().unwrap().parts().is_none());
    }

    /// parts is the OpenAI array shape; `image_ref` is vemry's own persisted form.
    #[test]
    fn content_parts_serialize_openai_shape() {
        let m = ChatMessage::user_content(Content::Parts(vec![
            Part::Text { text: "看图".into() },
            Part::ImageRef { path: "a.png".into() },
            Part::ImageUrl { image_url: ImageUrl { url: "data:image/png;base64,AA==".into() } },
        ]));
        let v = serde_json::to_value(&m).unwrap();
        assert_eq!(
            v["content"],
            json!([
                { "type": "text", "text": "看图" },
                { "type": "image_ref", "path": "a.png" },
                { "type": "image_url", "image_url": { "url": "data:image/png;base64,AA==" } }
            ])
        );
        let back: ChatMessage = serde_json::from_value(v).unwrap();
        assert_eq!(back.text(), Some("看图"), "the text view takes the first Text part");
        assert_eq!(back.content.as_ref().unwrap().parts().unwrap().len(), 3);
    }

    #[test]
    fn push_str_appends_to_last_text_part_or_adds_one() {
        let mut t = Content::Text("a".into());
        t.push_str("b");
        assert_eq!(t.text(), Some("ab"));
        let mut p = Content::Parts(vec![Part::Text { text: "x".into() }, Part::ImageRef { path: "i.png".into() }]);
        p.push_str("y");
        assert_eq!(p.text(), Some("xy"));
        let mut only_image = Content::Parts(vec![Part::ImageRef { path: "i.png".into() }]);
        assert_eq!(only_image.text(), None);
        only_image.push_str("note");
        assert_eq!(only_image.text(), Some("note"));
        assert_eq!(only_image.parts().unwrap().len(), 2);
    }
}
