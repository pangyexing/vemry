<script lang="ts">
  import { api, type SessionMeta } from "$lib/api";
  import { agent } from "$lib/stores/agent.svelte";
  import { vault } from "$lib/stores/vault.svelte";
  import { classifyDiff } from "$lib/views/diff";
  import { handleCodeCopyClick, renderAssistantMarkdownBlocks } from "$lib/markdown";
  import "katex/dist/katex.min.css";
  import { t } from "$lib/i18n/i18n.svelte";
  import {
    decisionLabel,
    displayTitle,
    editableTitle,
    formatSessionId,
    hhmmss,
    parseSession,
    planDecisionLabel,
    PLAN_GLYPH,
    renameKeydown,
    toolLabel,
    type SessionEntry,
  } from "$lib/views/session";
  import { contextMenu } from "$lib/stores/contextMenu.svelte";
  import { fuzzyKeep } from "$lib/commands/registry";
  import { skillTitleByName } from "$lib/skills";
  import type { ActionItem } from "$lib/api";
  import ViewHeader, { countLabel } from "./ViewHeader.svelte";
  import PrivacyIcon from "../PrivacyIcon.svelte";
  import DiffLines from "../DiffLines.svelte";
  import { cliptip } from "$lib/cliptip";
  import { langAttrs, noteLanguage } from "$lib/notelang";

  let sessions = $state<SessionMeta[]>([]);

  /** One proposed action item on a line, the way the live card prints a decided row. */
  function actionLine(a: ActionItem): string {
    const fields = a.fields ? Object.entries(a.fields).map(([k, v]) => ` · ${k} ${v}`).join("") : "";
    return `${a.text}${a.owner ? ` · ${a.owner}` : ""}${a.due ? ` · ${a.due}` : ""}${fields}${a.target ? ` → ${a.target}` : ""}`;
  }
  let query = $state("");
  let selected = $state<string | null>(null);
  let entries = $state<SessionEntry[]>([]);
  let expanded = $state<Record<number, boolean>>({});
  let replay = $state<HTMLDivElement | null>(null);
  /** The sessions the list held when it was first read or last looked at: one started since
   *  is marked in the list, and the replay stays on what the reader is reading. */
  let known = $state<Set<string> | null>(null);

  async function loadList() {
    try {
      // The same session list IPC as the research panel's (newest first, with the title and
      // the turn count); the replay's content still goes through the read-only session_read
      // — agent_session_select would switch the model context
      sessions = await api.agentSessionList();
    } catch (e) {
      vault.error = String(e);
    }
  }

  /** The filter key = the title plus the session id (an id is a timestamp, so "that one on
   *  19 August" can be found by date too).
   *  When the selected session is filtered out the replay on the right stays as it is —
   *  filtering narrows the list and does not overturn what is being read. */
  const shown = $derived(fuzzyKeep(sessions, query, (s) => `${displayTitle(s)} ${formatSessionId(s.id)}`));

  /** The user switches sessions: the expansion state and the render cache are reset, and
   *  the replay starts at the session's top (not at the scroll offset the previous one left) */
  async function select(id: string) {
    selected = id;
    expanded = {};
    htmlCache = new Map();
    if (known && !known.has(id)) known = new Set([...known, id]);
    if (replay) replay.scrollTop = 0;
    await reread(id);
  }

  /** Assistant messages are rendered memoised by content: reread rebuilds the whole entries
   *  array behind a debounce while the log only ever appends → the memo keeps the rendering
   *  cost on the new lines alone. numberOf is passed an empty Map, so links render as
   *  ordinary md-links and never produce a marker (the renderer only calls .get, which is
   *  read-only and safe).
   *  Only assistant.content goes through {@html} — user/tool_result/raw/diff are audit
   *  evidence, stay text nodes and never pass through {@html}. */
  const NO_CITES = new Map<string, number>();
  let htmlCache = new Map<string, { html: string; lang: ReturnType<typeof langAttrs> }>();
  /** The answer's HTML and what it reads as (fonts, line breaking and the column width
   *  follow the answer's own language), memoised together. */
  function assistantView(content: string): { html: string; lang: ReturnType<typeof langAttrs> } {
    let v = htmlCache.get(content);
    if (v == null) {
      v = { html: renderAssistantMarkdownBlocks(content, NO_CITES).join(""), lang: langAttrs(noteLanguage(content)) };
      htmlCache.set(content, v);
    }
    return v;
  }

  /** The rendered links and copy buttons go through click delegation (generated HTML cannot
   *  carry component events).
   *  A main-window view calls vault.followLink directly and needs none of AgentChat's
   *  hostDispatch relaying. */
  function onReplayClick(e: MouseEvent) {
    if (!(e.target instanceof Element)) return;
    if (handleCodeCopyClick(e)) return; // the code block's copy button (static HTML generated by markdown.ts)
    const el = e.target.closest("a[data-url], a[data-wiki]");
    if (!(el instanceof HTMLElement)) return;
    e.preventDefault();
    if (el.dataset.url) api.urlOpen(el.dataset.url, e.metaKey || e.ctrlKey, false).catch((err) => (vault.error = String(err)));
    else if (el.dataset.wiki) void vault.followLink(el.dataset.wiki);
  }

  /** "View the written blocks": open the note with the origin overlay on, and land on
   *  the first block still awaiting review (a note whose blocks were all accepted or
   *  rewritten since just opens). */
  async function openWritten(path: string) {
    vault.provenanceOverlay = true;
    await vault.openForReview(path, "first");
  }

  /** Reread the session's content while keeping the expansion state (the log only appends, so the indices of existing entries are stable) */
  async function reread(id: string) {
    try {
      const parsed = parseSession(await api.sessionRead(id));
      if (selected === id) entries = parsed;
    } catch (e) {
      if (selected === id) {
        entries = [];
        vault.error = String(e);
      }
    }
  }

  // Every discrete agent event triggers a refresh (behind a debounce): a running replay
  // follows the log as it grows rather than waiting for the run to end.
  // Opening the view shows the newest session; after that the replay stays on the session
  // being read, and a session that starts meanwhile is marked in the list instead of taking
  // the replay over (one click reads it).
  let refreshing = false;
  let queued = false;
  async function refresh() {
    if (refreshing) {
      queued = true;
      return;
    }
    refreshing = true;
    try {
      await loadList();
      if (known === null) known = new Set(sessions.map((s) => s.id));
      const head: string | undefined = sessions[0]?.id;
      if (head && selected === null) {
        await select(head);
      } else if (selected) {
        await reread(selected);
      }
    } finally {
      refreshing = false;
      if (queued) {
        queued = false;
        void refresh();
      }
    }
  }

  void refresh();

  $effect(() => {
    void agent.activity;
    const timer = setTimeout(() => void refresh(), 300);
    return () => clearTimeout(timer); // with events firing in quick succession the previous one is cleared → a trailing debounce
  });

  const argsPreview = (args: unknown) => {
    const s = JSON.stringify(args);
    return s === undefined ? "" : s.length > 120 ? s.slice(0, 120) + "…" : s;
  };

  // ---- the session row's context menu: rename (an inline input) / delete (the same store path as the research panel's) ----
  let renamingId = $state<string | null>(null);
  let renameEl = $state<HTMLInputElement | null>(null);

  function sessionMenu(e: MouseEvent, s: SessionMeta) {
    contextMenu.open(e, [
      { title: displayTitle(s) },
      { label: t("sessionsView.rename"), action: () => startRename(s.id) },
      { separator: true },
      { label: t("sessionsView.delete"), danger: true, confirm: t("sessionsView.deleteConfirm"), action: () => void removeSession(s.id) },
    ]);
  }
  function startRename(id: string) {
    renamingId = id;
    queueMicrotask(() => renameEl?.select());
  }
  const cancelRename = () => (renamingId = null);
  async function commitRename(id: string, value: string) {
    if (renamingId !== id) return; // Esc already cancelled it (the id is cleared before the blur fires)
    renamingId = null;
    const t = value.trim();
    const cur = sessions.find((s) => s.id === id);
    if (!t || t === cur?.title) return;
    try {
      await agent.renameSession(id, t); // activity++ refreshes this list through the debounced effect
    } catch (e) {
      vault.error = String(e);
    }
  }
  async function removeSession(id: string) {
    try {
      await agent.deleteSession(id);
      if (selected === id) {
        selected = null;
        entries = [];
      }
      await refresh();
    } catch (e) {
      vault.error = String(e);
    }
  }
</script>

<div class="view">
  <ViewHeader
    title={t("view.sessions")}
    total={countLabel(shown.length, sessions.length, "sessions.count")}
    hint={t("sessionsView.hint")}
    filterPlaceholder={t("sessionsView.filterPlaceholder")}
    bind:filter={query}
  />
  <div class="split">
    <aside class="list">
      {#each shown as s (s.id)}
        {#if renamingId === s.id}
          <div class="session">
            <input
              class="rename-input"
              bind:this={renameEl}
              value={editableTitle(s)}
              placeholder={t("sessionsView.titlePlaceholder")}
              spellcheck="false"
              onkeydown={(e) => renameKeydown(e, cancelRename)}
              onblur={(e) => void commitRename(s.id, e.currentTarget.value)}
            />
          </div>
        {:else}
          {@const fresh = known !== null && !known.has(s.id)}
          <button class="session" class:active={s.id === selected} onclick={() => select(s.id)} oncontextmenu={(e) => sessionMenu(e, s)}>
            <span class="s-title" use:cliptip={displayTitle(s)}
              >{#if fresh}<span class="s-new" title={t("sessionsView.newSession")} aria-label={t("sessionsView.newSession")}></span>{/if}{#if s.forked}<span
                  class="s-fork"
                  title={t("sessionsView.forked")}>⑂</span
                >{/if}{displayTitle(s)}</span
            >
            <span class="s-meta">{formatSessionId(s.id)}{s.turns ? ` · ${t("sessionsView.turns", { n: s.turns })}` : ""}</span>
          </button>
        {/if}
      {:else}
        <p class="empty">
          {#if query.trim()}{t("sessionsView.noMatch", { query })}{:else}{t("sessionsView.empty")}{/if}
        </p>
      {/each}
    </aside>
    <!-- svelte-ignore a11y_click_events_have_key_events, a11y_no_static_element_interactions -->
    <div class="replay" bind:this={replay} onclick={onReplayClick}>
      <!-- .rows keeps a press in the padding or a flex gap off the scroll container itself (the same WebKit anchor bug as AgentChat .turns) -->
      <div class="rows">
      {#each entries as e, i (i)}
        {#if e.kind === "user"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="msg user">
              {e.content}
              {#if e.page}<div class="faint" title={e.page.url}>📄 {e.page.title || e.page.url}</div>{/if}
            </div>
          </div>
        {:else if e.kind === "assistant"}
          {@const view = assistantView(e.content)}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="msg assistant md-body" {...view.lang}>
              {@html view.html}
              {#if e.tool_calls > 0}<span class="faint">{t("sessionsView.calledTools", { n: e.tool_calls })}</span>{/if}
            </div>
          </div>
        {:else if e.kind === "tool_call"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="ledger">
              <span class="mark">▸</span>
              <span class="tool">{toolLabel(e.tool)}</span>
              <span class="args">{argsPreview(e.args)}</span>
            </div>
          </div>
        {:else if e.kind === "tool_result"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="result-wrap">
              <button class="ledger clickable" onclick={() => (expanded[i] = !expanded[i])}>
                <span class="mark" class:err={!e.ok}>{e.ok ? "✓" : "✕"}</span>
                <span class="tool">{toolLabel(e.tool)}</span>
                <span class="args">{expanded[i] ? t("sessionsView.collapse") : t("sessionsView.expandResult")}</span>
              </button>
              {#if expanded[i]}
                <pre class="output">{e.output}</pre>
              {/if}
            </div>
          </div>
        {:else if e.kind === "write_prepared"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="write">
              <div class="write-head">
                <span class="tool">{toolLabel(e.tool)}</span>
                <button class="path" onclick={() => vault.openNote(e.path)}>{e.path}</button>
                {#if e.to}
                  <span class="faint">→</span>
                  <button class="path" onclick={() => vault.openNote(e.to!)}>{e.to}</button>
                {/if}
              </div>
              {#if e.diff}
                <pre class="diff"><DiffLines lines={classifyDiff(e.diff)} /></pre>
              {:else if !e.to}
                <span class="faint">{t("permission.newFile")}</span>
              {/if}
              {#if !e.to}
                <button class="link" onclick={() => void openWritten(e.path)}>{t("sessionsView.viewWrittenBlocks")}</button>
              {/if}
            </div>
          </div>
        {:else if e.kind === "permission"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="write">
              <div class="permission">
                <span class="badge" class:deny={e.decision === "deny"}
                  >{e.decision === "allow_scope" && e.scope ? t("sessionsView.allowScope", { scope: e.scope }) : decisionLabel(e.decision)}{e.via === "follow"
                    ? t("sessionsView.viaFollow")
                    : e.via === "scope"
                      ? t("sessionsView.viaScope")
                      : ""}</span
                >
                <span class="path-text">{e.path}</span>
              </div>
              {#if e.applied_diff}
                <span class="faint">{t("sessionsView.appliedDiff")}</span>
                <pre class="diff"><DiffLines lines={classifyDiff(e.applied_diff)} /></pre>
              {/if}
            </div>
          </div>
        {:else if e.kind === "plan"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="write">
              <div class="write-head"><span class="tool">{t("tool.propose_plan")}</span></div>
              {#each e.items as p, j (j)}
                <div class="ws-link"><span class="ws-n">{j + 1}</span><span class="ws-title">{p}</span></div>
              {/each}
            </div>
          </div>
        {:else if e.kind === "plan_decision"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="permission">
              <span class="badge" class:deny={e.decision === "reject"}>
                {planDecisionLabel(e.decision)}
              </span>
              {#if e.reason}<span class="path-text">{e.reason}</span>{/if}
              {#if e.items?.length}<span class="path-text">{e.items.join(" / ")}</span>{/if}
            </div>
          </div>
        {:else if e.kind === "privacy"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="privacy">
              <PrivacyIcon size={12} />
              {t("sessionsView.privacyFiltered", { n: e.filtered, tool: toolLabel(e.tool) })}
            </div>
          </div>
        {:else if e.kind === "web_search"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            {#if e.queries}
              <div class="ledger">
                <span class="mark">▸</span>
                <span class="tool">{t("sessionsView.webSearch")}</span>
                <span class="args" title={e.queries.join("\n")}>{e.queries.join(" · ")}</span>
              </div>
            {:else}
              <div class="websearch">
                <div class="ledger">
                  <span class="mark">✓</span>
                  <span class="tool">{t("sessionsView.webSearch")}</span>
                  <span class="args">{t("sessionsView.webSearchResults", { n: e.count ?? e.links?.length ?? 0 })}</span>
                </div>
                {#each e.links ?? [] as link, j (j)}
                  <div class="ws-link" title={link.url}>
                    <span class="ws-n">{j + 1}</span>
                    <span class="ws-title">{link.title || link.url}</span>
                    {#if link.title}<span class="ws-url">{link.url}</span>{/if}
                  </div>
                {/each}
              </div>
            {/if}
          </div>
        {:else if e.kind === "follow"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="privacy">{e.path ? t("sessionsView.follow", { path: e.path }) : t("sessionsView.followEnd")}</div>
          </div>
        {:else if e.kind === "plan_update"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="write">
              <div class="write-head">
                <span class="tool">{t("sessionsView.planUpdate", { done: e.items.filter((p) => p.status === "done" || p.status === "skipped").length, total: e.items.length })}</span>
              </div>
              {#each e.items as p, j (j)}
                <div class="ws-link" class:faint={p.status === "skipped"}>
                  <span class="ws-n">{PLAN_GLYPH[p.status] ?? "☐"}</span>
                  <span class="ws-title">{p.text}</span>
                </div>
              {/each}
            </div>
          </div>
        {:else if e.kind === "sources"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="websearch">
              <div class="ledger">
                <span class="mark">✓</span>
                <span class="tool">{t("sessionsView.sourcesSettled", { n: e.items.length })}</span>
              </div>
              {#each e.items as src, j (j)}
                <div class="ws-link" title={src.url}>
                  <span class="ws-n">{j + 1}</span>
                  <span class="ws-title">{src.title || src.url}</span>
                  {#if !src.verified}<span class="ws-url">{t("chat.unverified")}</span>{:else if src.title}<span class="ws-url">{src.url}</span>{/if}
                </div>
              {/each}
            </div>
          </div>
        {:else if e.kind === "retry" || e.kind === "edit_resend" || e.kind === "compact" || e.kind === "fork" || e.kind === "effort"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="privacy">
              {e.kind === "retry"
                ? t("sessionsView.markRetry")
                : e.kind === "edit_resend"
                  ? t("sessionsView.markEditResend")
                  : e.kind === "compact"
                    ? t("sessionsView.markCompact", { level: t(e.level === 2 ? "sessionsView.compactSummary" : "sessionsView.compactHandles") })
                    : e.kind === "effort"
                      ? t(e.retaken === "answer" ? "sessionsView.markEffortAnswer" : "sessionsView.markEffortWork")
                      : t("sessionsView.markFork", { from: e.from, turn: e.before_turn + 1 })}
            </div>
          </div>
        {:else if e.kind === "actions"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="write">
              <div class="write-head"><span class="tool">{t("sessionsView.actions", { n: e.items.length })}</span></div>
              {#each e.items as a, j (j)}
                <div class="ws-link"><span class="ws-n">{j + 1}</span><span class="ws-title">{actionLine(a)}</span></div>
              {/each}
            </div>
          </div>
        {:else if e.kind === "actions_decision"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="write">
              <div class="permission">
                <span class="badge" class:deny={e.decision === "reject"}>
                  {e.decision === "approve" ? t("sessionsView.actionsDecision.approve", { n: e.items?.length ?? 0 }) : t("sessionsView.actionsDecision.reject")}
                </span>
                {#if e.reason}<span class="path-text">{e.reason}</span>{/if}
              </div>
              <!-- The kept list as the user edited it (the proposal above is what the model asked for) -->
              {#each e.items ?? [] as a, j (j)}
                <div class="ws-link"><span class="ws-n">{j + 1}</span><span class="ws-title">{actionLine(a)}</span></div>
              {/each}
            </div>
          </div>
        {:else if e.kind === "read"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="write">
              <div class="write-head"><span class="tool">{t("sessionsView.read", { n: e.urls.length })}</span></div>
              {#each e.urls as u, j (j)}
                <div class="ws-link" title={u}><span class="ws-n">{j + 1}</span><span class="ws-title">{u}</span></div>
              {/each}
            </div>
          </div>
        {:else if e.kind === "read_decision"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="write">
              <div class="permission">
                <span class="badge" class:deny={e.decision === "deny"}>
                  {e.decision === "pages"
                    ? `${t("sessionsView.readDecision.pages", { n: e.urls?.length ?? 0 })}${e.auto ? t("sessionsView.readAuto") : ""}`
                    : t("sessionsView.readDecision.deny")}
                </span>
                {#if e.reason}<span class="path-text">{e.reason}</span>{/if}
              </div>
              {#if e.failed?.length}
                <span class="faint">{t("sessionsView.readFailed", { n: e.failed.length })}</span>
                {#each e.failed as u, j (j)}
                  <div class="ws-link" title={u}><span class="ws-n">✕</span><span class="ws-title">{u}</span></div>
                {/each}
              {/if}
            </div>
          </div>
        {:else if e.kind === "read_auto"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="privacy">{t("sessionsView.readAutoOn")}</div>
          </div>
        {:else if e.kind === "undo"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="privacy">{t("sessionsView.undo", { n: e.reverted, skipped: e.skipped })}</div>
          </div>
        {:else if e.kind === "skill"}
          <div class="row">
            <span class="ts">{hhmmss(e.ts)}</span>
            <div class="privacy">{t("sessionsView.skill", { name: skillTitleByName(e.name) })}{t(e.via === "read" ? "sessionsView.skillRead" : "sessionsView.skillAttached")}</div>
          </div>
        {:else if e.kind === "title" || e.kind === "grants_cleared"}
          <!-- Pure metadata, not rendered in the replay (an explicit branch pins the intent): a
               rename's title override line; the marker Rust reads back when the session's grants were revoked -->
        {:else if e.kind === "raw"}
          <div class="row">
            <span class="ts"></span>
            <pre class="raw">{e.text}</pre>
          </div>
        {:else}
          <!-- A kind this build does not know (a log written by a newer version): shown as its line rather than dropped -->
          <div class="row">
            <span class="ts"></span>
            <pre class="raw">{JSON.stringify(e)}</pre>
          </div>
        {/if}
      {:else}
        {#if selected}
          <p class="empty">{t("sessionsView.nothingToShow")}</p>
        {:else}
          <p class="empty">{t("sessionsView.pickSession")}</p>
        {/if}
      {/each}
      </div>
    </div>
  </div>
</div>

