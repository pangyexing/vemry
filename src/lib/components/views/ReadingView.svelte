<script lang="ts">
  // The reading projection (v0.5 P2): a citation click lands here by default — the hidden
  // reader window fetches, the clip pipeline extracts the body, and the main window renders
  // it. A visible browser window is the interactive escape hatch (paywalls, logins, complex
  // pages).
  import { t } from "$lib/i18n/i18n.svelte";
  import { api } from "$lib/api";
  import { executeCommand } from "$lib/commands/registry";
  import { reading } from "$lib/stores/reading.svelte";
  import { vault } from "$lib/stores/vault.svelte";
  import { agent } from "$lib/stores/agent.svelte";
  import { clips } from "$lib/stores/clips.svelte";
  import { clipTarget } from "$lib/stores/clipTarget.svelte";
  import { toast } from "$lib/stores/toast.svelte";
  import { domainOf, handleCodeCopyClick, imageChip, renderReadingMarkdown } from "$lib/markdown";
  import { openImageLightbox } from "$lib/lightbox";
  import { k } from "$lib/shortcut";
  import "katex/dist/katex.min.css";

  let {
    onPickQuoteTarget,
  }: {
    /** ⌥-clicking "selection → note": the quote block is already composed, and App raises the pick-note panel to choose a target. */
    onPickQuoteTarget?: (quote: string, sourceUrl?: string) => void;
  } = $props();

  let scroller = $state<HTMLDivElement | null>(null);
  let article = $state<HTMLElement | null>(null);

  const run = (p: Promise<unknown>) => void p.catch((e) => toast.push(String(e), "error"));
  const cur = $derived(reading.current);

  // The scroll position is restored when the page changes, and onscroll keeps recording it
  // otherwise. restoring blocks the scroll event the restoring itself fires, so the old page's
  // position is not recorded against the new page
  let restoring = false;
  let shownUrl: string | null = null;
  $effect(() => {
    const url = cur?.url ?? null;
    if (!scroller || url === shownUrl) return;
    shownUrl = url;
    if (url) {
      restoring = true;
      scroller.scrollTop = reading.scrollFor(url);
      requestAnimationFrame(() => (restoring = false));
    }
  });
  function onscroll() {
    if (!restoring && scroller && cur) reading.saveScroll(cur.url, scroller.scrollTop);
  }

  // A failed image load (hotlink protection, an expired signature, the proxy switched off) →
  // back to a placeholder chip. The error event does not bubble, so the listener is attached
  // in the capture phase; a chip click goes through onArticleClick's md-img branch
  $effect(() => {
    const el = article;
    if (!el) return;
    const onError = (e: Event) => {
      const img = e.target;
      if (!(img instanceof HTMLImageElement) || !img.dataset.url) return;
      const holder = document.createElement("span");
      holder.innerHTML = imageChip(img.dataset.url, img.alt || t("reader.image"));
      if (holder.firstElementChild) img.replaceWith(holder.firstElementChild);
    };
    el.addEventListener("error", onError, true);
    return () => el.removeEventListener("error", onError, true);
  });

  /** A link inside the projection: already clipped → the local note; otherwise it stays in the
   *  projection (keeping the reading flow); ⌘click takes the escape hatch (url_open invert,
   *  which always gives a real browser). An image click always opens the lightbox in the
   *  current window (as in the editor; with or without ⌘ it never jumps to a window, and the
   *  proxied src already shown makes no further request); only a failed load's placeholder chip
   *  opens a browser window to see the original. */
  function onArticleClick(e: MouseEvent) {
    if (!(e.target instanceof Element)) return;
    if (handleCodeCopyClick(e)) return; // the code block's copy button (static HTML generated by markdown.ts)
    const el = e.target.closest("a[data-url], img[data-url]");
    if (!(el instanceof HTMLElement) || !el.dataset.url) return;
    e.preventDefault();
    const url = el.dataset.url;
    if (el instanceof HTMLImageElement) {
      openImageLightbox(el.currentSrc || el.src, el.alt);
      return;
    }
    if (el.classList.contains("md-img")) {
      run(api.browserOpen(url));
      return;
    }
    if (e.metaKey || e.ctrlKey) {
      run(api.urlOpen(url, true, false));
      return;
    }
    const local = clips.pathFor(url);
    if (local) void vault.openNote(local);
    else void reading.open(url);
  }

  async function clip() {
    if (!cur) return;
    try {
      const path = await api.readingClip(cur.url);
      clips.markClipped(cur.url, path);
      toast.push(t("reader.clipped", { path }));
    } catch (e) {
      toast.push(String(e), "error");
    }
  }

  function openClipped() {
    const p = cur && clips.pathFor(cur.url);
    if (p) void vault.openNote(p);
  }

  /** A selection's DOM fragment → HTML that can be converted to Markdown. The projection's
   *  rendering is restored to its original form: a proxied image or a placeholder chip goes
   *  back to the original address in its data-url (only then can htmd produce `![](url)`, and
   *  only then does the later localisation recognise it), a link gets its href back, and
   *  KaTeX's output falls back to plain text (the projection renders with output:"html", so
   *  the DOM holds no TeX source to restore — the same degradation as a plain-text
   *  selection). */
  function selectionFragmentHtml(sel: Selection): string {
    if (!sel.rangeCount || sel.isCollapsed) return "";
    const box = document.createElement("div");
    for (let i = 0; i < sel.rangeCount; i++) box.appendChild(sel.getRangeAt(i).cloneContents());
    for (const el of box.querySelectorAll(".katex-display, .katex")) {
      el.replaceWith(document.createTextNode(el.textContent ?? ""));
    }
    for (const img of box.querySelectorAll("img[data-url]")) {
      img.setAttribute("src", img.getAttribute("data-url") ?? "");
    }
    for (const chip of box.querySelectorAll("a.md-img[data-url]")) {
      const img = document.createElement("img");
      img.setAttribute("src", chip.getAttribute("data-url") ?? "");
      img.setAttribute("alt", (chip.textContent ?? "").replace(/^⧉\s*/, ""));
      chip.replaceWith(img);
    }
    for (const link of box.querySelectorAll("a.md-link[data-url]")) {
      link.setAttribute("href", link.getAttribute("data-url") ?? "");
    }
    return box.innerHTML;
  }

  /** A selection → a quote block. While the projection holds the main pane the editor is only
   *  hidden by CSS, and a bare insertAtCursor would silently write into that invisible old
   *  note — so it passes the shared guard, and when it is not visible it lands in the inbox
   *  and says so. The selection is right here in the main webview — the button's mousedown
   *  prevents the default, so clicking does not collapse the selection. */
  async function quoteSelection(pickTarget = false) {
    if (!cur) return;
    const sel = window.getSelection();
    const text = sel ? String(sel) : "";
    if (!text.trim() || !sel || !article?.contains(sel.anchorNode)) {
      toast.push(t("reader.selectFirst"), "error");
      return;
    }
    try {
      const quote = await api.readingQuote(cur.url, text, selectionFragmentHtml(sel));
      // ⌥ or ▾: choose the target note. The text is already in hand, so the panel taking the focus and collapsing the selection does not matter
      if (pickTarget && onPickQuoteTarget) {
        onPickQuoteTarget(quote, cur.url);
        return;
      }
      // The pinned destination wins: choose once and deliver many times (including the pinned
      // section); when the target has been deleted the pin is released (ensureLive has already
      // said so) and it falls back to the default destination (fresh: so a lagging notes mirror
      // does not wrongly kill a note that was just created and pinned)
      if ((await clipTarget.ensureLiveFresh()) && clipTarget.path) {
        await clipTarget.deliver(clipTarget.path, quote, cur.url, clipTarget.heading);
        return;
      }
      // Both routes go through deliver: the order contract of inserting or appending, flushing
      // and localising the images is maintained once.
      // When it is not visible, vault.capture cannot be used — its single-line list-item
      // template (`- text *(time)*`) would twist a multi-line quote block into broken Markdown,
      // while deliver's noteInsert lands the whole block verbatim
      if (vault.canInsertIntoVisibleNote && vault.currentPath) {
        await clipTarget.deliver(vault.currentPath, quote, cur.url);
      } else if (await clipTarget.deliver("inbox.md", quote, cur.url)) {
        toast.push(t("reader.savedToInbox"));
      }
    } catch (e) {
      toast.push(String(e), "error");
    }
  }

  /** "Add to context" is purely frontend: the projection's body is already in hand (the
   *  assembly and the proxy-pair trimming live in the reading store's pageContext, shared with
   *  the @ picker), and the chip is attached to the shared draft. */
  function attachContext() {
    const page = reading.pageContext();
    if (!page) return;
    agent.attachPage(page);
    vault.rightOpen = true;
    vault.rightTab = "agent";
    toast.push(t("reader.attachedToContext"));
  }

  /** The escape hatch: a visible browser window loads the original page (interaction, images and paywalls all belong to it). */
  function openInBrowser(url: string) {
    run(api.browserOpen(url));
  }

  /** ←/→ and ⌘⌥←/→ are exactly the same implementation: the layered rule of projection stack
   *  → document history → where it came from is maintained once, in the nav-back / nav-forward
   *  commands App.svelte registers (this view only renders while mainView === "reading", so the
   *  command necessarily takes the projection branch). */
  function goBack() {
    void executeCommand("nav-back");
  }

  function goForward() {
    void executeCommand("nav-forward");
  }
</script>

<div class="view">
  <header>
    <span class="nav">
      <button
        title={reading.canGoBack || vault.canGoBack ? t("tabBar.backWithKey", { key: k("Mod+Alt+←") }) : t("reader.backToOrigin", { key: k("Mod+Alt+←") })}
        aria-label={t("common.back")}
        onclick={goBack}
      >←</button>
      <button
        title={t("tabBar.forwardWithKey", { key: k("Mod+Alt+→") })}
        aria-label={t("common.forward")}
        disabled={!reading.canGoForward && !vault.canGoForward}
        onclick={goForward}
      >→</button>
    </span>
    {#if cur}
      <span class="title" title={cur.url}>{cur.title || domainOf(cur.url)}</span>
      <span class="domain">{domainOf(cur.url)}</span>
      <span class="actions">
        {#if clips.pathFor(cur.url)}
          <button class="clipped" title={t("reader.alreadyClippedHint")} onclick={openClipped}>{t("reader.alreadyClipped")}</button>
        {:else}
          <button title={t("reader.clipHint")} onclick={() => void clip()}>{t("reader.clip")}</button>
        {/if}
        <button
          class="target"
          title={clipTarget.path
            ? t("reader.selectionToTargetHint", { path: clipTarget.path, key: k("Alt") })
            : t("reader.selectionToInboxHint", { key: k("Alt") })}
          onmousedown={(e) => e.preventDefault()}
          onclick={(e) => void quoteSelection(e.altKey)}
        >{t("reader.selectionToTarget", { name: clipTarget.name ?? t("reader.note") })}</button>
        <button
          class="mini"
          title={t("reader.pickTargetHint")}
          onmousedown={(e) => e.preventDefault()}
          onclick={() => void quoteSelection(true)}
        >▾</button>
        {#if clipTarget.path}
          <button class="mini" title={t("reader.clearTargetHint")} onclick={() => clipTarget.clear()}>✕</button>
        {/if}
        <button title={t("reader.addToContextHint")} onclick={attachContext}>{t("reader.addToContext")}</button>
        <button title={t("reader.openInBrowserHint")} onclick={() => openInBrowser(cur.url)}>{t("reader.openInBrowser")}</button>
        <button title={t("reader.openInSystemBrowser")} aria-label={t("reader.openInSystemBrowser")} onclick={() => run(api.urlOpenSystem(cur.url))}>↗</button>
      </span>
    {:else}
      <span class="title faint">{t("view.reading")}</span>
    {/if}
    <button class="close" title={t("reader.leaveHint")} aria-label={t("reader.leave")} onclick={() => vault.exitReading()}>✕</button>
  </header>

  {#if reading.loading}
    <div class="state">
      <span class="pulse"></span>
      {t("reader.extracting", { domain: domainOf(reading.loading) })}
      <button class="ghost" onclick={() => reading.loading && openInBrowser(reading.loading)}>{t("reader.openInBrowserInstead")}</button>
    </div>
  {:else if reading.error}
    <div class="state error">
      <p>{reading.error.message}</p>
      <div class="state-actions">
        <button class="ghost" onclick={() => reading.retry()}>{t("reader.retry")}</button>
        <button class="ghost" onclick={() => reading.error && openInBrowser(reading.error.url)}>{t("reader.openInBrowser")}</button>
        <button class="ghost" onclick={() => reading.error && run(api.urlOpenSystem(reading.error.url))}>{t("reader.systemBrowser")}</button>
      </div>
    </div>
  {:else if cur}
    {#if cur.fallback}
      <div class="banner">
        {t("reader.degraded")}
        <button class="ghost" onclick={() => openInBrowser(cur.url)}>{t("reader.viewOriginal")}</button>
      </div>
    {/if}
    <div class="scroller" bind:this={scroller} {onscroll}>
      <!-- svelte-ignore a11y_click_events_have_key_events, a11y_no_noninteractive_element_interactions -->
      <article bind:this={article} onclick={onArticleClick}>
        {@html renderReadingMarkdown(cur.markdown, cur.url)}
      </article>
      <footer class="src">
        {t("reader.source")}<a class="src-link" href={cur.url} onclick={(e) => { e.preventDefault(); openInBrowser(cur.url); }}>{cur.url}</a>
        {#if cur.byline}<span> · {cur.byline}</span>{/if}
      </footer>
    </div>
  {:else}
    <div class="state faint">{t("reader.empty")}</div>
  {/if}
</div>

